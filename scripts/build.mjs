#!/usr/bin/env node
// Build pipeline for cc-harness.
//   node scripts/build.mjs [--watch]
//
// Produces dist/, which is committed so the plugin needs no install step.
// A one-shot build stages into a temporary directory and swaps it in only
// once every bundle has succeeded — a failed build must never leave the
// installed plugin without a UI.
import * as esbuild from 'esbuild';
import { cp, mkdir, readdir, rm, readFile, writeFile, rename } from 'node:fs/promises';
import * as tailwind from '@tailwindcss/node';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const watch = process.argv.includes('--watch');

const dist = path.join(root, 'dist');
// Watch mode writes in place so the running daemon picks changes up.
const outRoot = watch ? dist : path.join(root, '.build');
const previous = path.join(root, '.build-previous');

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

const common = {
  bundle: true,
  sourcemap: true,
  logLevel: 'info',
  define: { __HARNESS_VERSION__: JSON.stringify(pkg.version) },
};

/** Node-side bundles: self-contained, no runtime dependencies. */
const nodeBundles = [
  { in: 'src/daemon/main.ts', out: 'daemon/main.js' },
  { in: 'src/mcp/main.ts', out: 'mcp/main.js' },
  { in: 'src/cli/main.ts', out: 'cli/main.js' },
];

const configs = nodeBundles.map((b) => ({
  ...common,
  entryPoints: [path.join(root, b.in)],
  outfile: path.join(outRoot, b.out),
  platform: 'node',
  target: 'node20.11',
  format: 'esm',
  banner: { js: `#!/usr/bin/env node\n// cc-harness v${pkg.version} — generated by scripts/build.mjs` },
}));

/** The browser bundle: React, compiled once and shipped verbatim. */
configs.push({
  ...common,
  entryPoints: [path.join(root, 'src/ui/main.tsx')],
  outfile: path.join(outRoot, 'ui/app.js'),
  platform: 'browser',
  target: 'es2022',
  format: 'iife',
  jsx: 'automatic',
  minify: !watch,
  define: { ...common.define, 'process.env.NODE_ENV': watch ? '"development"' : '"production"' },
});

if (existsSync(path.join(root, 'src/test'))) {
  configs.push({
    ...common,
    entryPoints: [path.join(root, 'src/test/*.test.ts'), path.join(root, 'src/test/*.test.tsx')],
    entryNames: '[name]',
    outdir: path.join(outRoot, 'test'),
    platform: 'node',
    target: 'node20.11',
    format: 'esm',
    jsx: 'automatic',
    // Test-only dependencies (jsdom, React, Testing Library) resolve from
    // node_modules at run time: jsdom uses dynamic require and cannot be
    // bundled. The shipped bundles above stay fully self-contained.
    packages: 'external',
    define: { ...common.define, 'process.env.NODE_ENV': '"development"' },
  });
}

/**
 * The stylesheet is a Tailwind v4 entry, so it is compiled rather than
 * copied: Tailwind scans src/ui for class names and emits only what is used.
 * Run in-process rather than by shelling out to the CLI, so a failure throws
 * here and the staged build is discarded like any other failure.
 */
async function buildCss() {
  const input = path.join(root, 'src/ui/style.css');
  const compiler = await tailwind.compile(await readFile(input, 'utf8'), {
    base: path.dirname(input),
    onDependency() {},
  });
  const candidates = await scanCandidates(path.join(root, 'src/ui'));
  return compiler.build(candidates);
}

/**
 * Every identifier-shaped token in the templates, handed to Tailwind as a
 * candidate. Over-collecting is free — a candidate that is not a utility
 * generates nothing — while under-collecting silently drops a style.
 */
async function scanCandidates(dir) {
  const found = new Set();
  for (const entry of await readdir(dir, { withFileTypes: true, recursive: true })) {
    if (!entry.isFile() || !/\.(tsx?|html)$/.test(entry.name)) continue;
    const text = await readFile(path.join(entry.parentPath ?? entry.path, entry.name), 'utf8');
    for (const token of text.match(/[A-Za-z0-9!@_%+.:[\]/-]{2,}/g) ?? []) found.add(token);
  }
  return [...found];
}

async function copyStatic() {
  await mkdir(path.join(outRoot, 'ui'), { recursive: true });
  await cp(path.join(root, 'src/ui/index.html'), path.join(outRoot, 'ui/index.html'));
  // React Flow's own stylesheet, loaded before ours so the app's theme wins.
  await cp(path.join(root, 'node_modules/@xyflow/react/dist/style.css'), path.join(outRoot, 'ui/flow.css'));
  await writeFile(path.join(outRoot, 'ui/style.css'), await buildCss());
  await writeFile(path.join(outRoot, 'version.json'), JSON.stringify({ version: pkg.version }, null, 2));
}

if (watch) {
  const contexts = await Promise.all(configs.map((c) => esbuild.context(c)));
  await copyStatic();
  await Promise.all(contexts.map((c) => c.watch()));
  console.log('[build] watching…');
} else {
  await rm(outRoot, { recursive: true, force: true });
  await rm(previous, { recursive: true, force: true });

  // Any failure here throws before dist/ is touched.
  await Promise.all(configs.map((c) => esbuild.build(c)));
  await copyStatic();

  if (existsSync(dist)) await rename(dist, previous);
  await rename(outRoot, dist);
  await rm(previous, { recursive: true, force: true });
  console.log(`[build] dist/ written (v${pkg.version})`);
}
